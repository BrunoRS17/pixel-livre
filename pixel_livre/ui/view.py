"""Declarative window layout, kept separate from actions and application state."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QAbstractItemView, QComboBox, QFrame, QHBoxLayout, QHeaderView, QLineEdit,
    QLayout, QProgressBar, QPushButton, QScrollArea, QTableWidget, QVBoxLayout, QWidget,
)
from .components import DropZone, label


def card() -> tuple[QFrame, QVBoxLayout]:
    frame = QFrame()
    frame.setObjectName('card')
    layout = QVBoxLayout(frame)
    layout.setContentsMargins(22, 20, 22, 20)
    layout.setSpacing(12)
    layout.setSizeConstraint(QLayout.SizeConstraint.SetMinimumSize)
    return frame, layout


class WindowView(QWidget):
    """Expose named controls for the window controller without processing files."""
    def __init__(self):
        super().__init__()
        self.setObjectName('root')
        outer = QVBoxLayout(self)
        outer.setContentsMargins(28, 22, 28, 22)
        outer.setSpacing(18)
        header = QHBoxLayout()
        header.addWidget(label('◈  Pixel Livre', 'brand'))
        header.addStretch()
        header.addWidget(label('●  Processamento local', 'badge'))
        outer.addLayout(header)
        heading = QVBoxLayout()
        heading.setSpacing(4)
        heading.addWidget(label('Menos dados. Mais privacidade.', 'title'))
        heading.addWidget(label('Prepare suas imagens para compartilhar, mantendo os originais intactos.', 'muted', True))
        outer.addLayout(heading)

        columns = QHBoxLayout()
        columns.setSpacing(20)
        outer.addLayout(columns, 1)
        library, left = card()
        library_scroll = QScrollArea()
        library_scroll.setWidgetResizable(True)
        library_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        library_scroll.setWidget(library)
        columns.addWidget(library_scroll, 3)
        left.addWidget(label('01 / IMPORTAR', 'step'))
        self.drop_zone = DropZone()
        left.addWidget(self.drop_zone)
        actions = QHBoxLayout()
        self.add_files = QPushButton('+  Imagens')
        self.add_folder = QPushButton('Adicionar pasta')
        actions.addWidget(self.add_files)
        actions.addWidget(self.add_folder)
        actions.addStretch()
        left.addLayout(actions)
        left.addWidget(label('PNG, JPEG, WebP, BMP e TIFF • sem incluir subpastas', 'muted', True))
        list_header = QHBoxLayout()
        self.count = label('Sua seleção · 0', 'section')
        list_header.addWidget(self.count)
        list_header.addStretch()
        self.remove = QPushButton('Remover')
        self.remove.setObjectName('quiet')
        self.remove.setToolTip('Remover imagens selecionadas da lista (Delete)')
        list_header.addWidget(self.remove)
        left.addLayout(list_header)
        self.table = QTableWidget(0, 2)
        self.table.setHorizontalHeaderLabels(['IMAGEM', 'RESULTADO'])
        self.table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
        self.table.horizontalHeader().setSectionResizeMode(1, QHeaderView.ResizeMode.Stretch)
        self.table.verticalHeader().hide()
        self.table.verticalHeader().setDefaultSectionSize(46)
        self.table.setShowGrid(False)
        self.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        self.table.setSelectionMode(QAbstractItemView.SelectionMode.ExtendedSelection)
        self.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.setMinimumHeight(120)
        self.table.setAccessibleName('Imagens selecionadas e resultados da limpeza')
        left.addWidget(self.table, 1)
        self.empty = label('Sua próxima imagem começa aqui.\nArraste um arquivo para a área acima.', 'muted', True)
        self.empty.setAlignment(Qt.AlignmentFlag.AlignCenter)
        left.addWidget(self.empty)
        self.import_status = label('Selecione uma imagem para conferir a prévia.', 'muted', True)
        left.addWidget(self.import_status)

        # Scroll the settings panel on short displays without hiding the main action.
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setMinimumWidth(330)
        scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        columns.addWidget(scroll, 2)
        right, panel = card()
        scroll.setWidget(right)
        panel.addWidget(label('02 / CONFERIR E EXPORTAR', 'step'))
        self.preview = label('Prévia da imagem', 'preview')
        self.preview.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.preview.setFixedHeight(160)
        panel.addWidget(self.preview)
        self.details = label('Selecione um arquivo na lista.', 'muted', True)
        self.details.setMinimumHeight(64)
        self.details.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
        panel.addWidget(self.details)
        panel.addWidget(label('Onde salvar', 'section'))
        self.destination = QLineEdit()
        self.destination.setPlaceholderText('Escolha uma pasta de destino')
        self.destination.setAccessibleName('Pasta de destino das imagens limpas')
        panel.addWidget(self.destination)
        self.choose_folder = QPushButton('Escolher pasta de saída')
        panel.addWidget(self.choose_folder)
        panel.addWidget(label('A última pasta escolhida será lembrada.', 'muted', True))
        panel.addWidget(label('Formato de saída', 'section'))
        self.output_format = QComboBox()
        self.output_format.addItem('PNG · Sem perdas', 'PNG')
        self.output_format.addItem('JPEG · Arquivo compacto', 'JPEG')
        self.output_format.addItem('WebP · Sem perdas', 'WEBP')
        self.output_format.setAccessibleName('Formato de saída')
        panel.addWidget(self.output_format)
        self.format_hint = label('', 'muted', True)
        panel.addWidget(self.format_hint)
        panel.addWidget(label('Seus originais ficam intactos. As cópias recebem o sufixo _limpa.', 'muted', True))
        panel.addStretch()

        footer, bottom = card()
        outer.addWidget(footer)
        row = QHBoxLayout()
        summary = QVBoxLayout()
        summary.setSpacing(4)
        self.status = label('Tudo pronto para começar', 'section', True)
        summary.addWidget(self.status)
        summary.addWidget(label('Limpa metadados. Textos e marcas d’água visíveis permanecem.', 'muted', True))
        row.addLayout(summary, 1)
        self.open_folder = QPushButton('Abrir pasta')
        self.cancel = QPushButton('Cancelar')
        self.cancel.hide()
        self.start = QPushButton('Limpar imagens  →')
        self.start.setObjectName('primary')
        row.addWidget(self.open_folder)
        row.addWidget(self.cancel)
        row.addWidget(self.start)
        bottom.addLayout(row)
        self.progress = QProgressBar()
        self.progress.setRange(0, 100)
        self.progress.setValue(0)
        self.progress.setTextVisible(False)
        bottom.addWidget(self.progress)
